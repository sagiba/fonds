import { randomUUID } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";

import { createClient } from "@libsql/client/node";
import { Pool } from "pg";

import type { Migration } from "../src/storage/migrations.js";
import {
  ensurePostgresSchema,
  FINANCIAL_SCHEMA,
  migratePostgresSchema,
} from "../src/storage/postgres/initialize.js";
import {
  operationsInspectionSql,
  schemaInspectionSql,
} from "../src/storage/postgres/schema-check.js";
import { migrateSqliteSchema } from "../src/storage/sqlite/migrate.js";

const check = process.argv.includes("--check");
if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new Error("Usage: tsx scripts/generate-storage-schema.ts [--check]");
}
const connectionString = process.env.FONDS_TEST_POSTGRES_URL;
if (!connectionString?.trim()) {
  throw new Error(
    "Set FONDS_TEST_POSTGRES_URL to a disposable PostgreSQL 18 database",
  );
}
/** Hosts of a disposable server on this machine or its container host. */
const localTestHosts = [
  "localhost",
  "127.0.0.1",
  "[::1]",
  "host.docker.internal",
];
if (!localTestHosts.includes(new URL(connectionString).hostname)) {
  throw new Error("Schema generation requires a local disposable database");
}

const root = new URL("../", import.meta.url);

/** `NNNN_name.sql` files numbered 1, 2, 3… with no gaps. */
async function readMigrations(directory: string): Promise<Migration[]> {
  const files = (await readdir(new URL(directory, root)))
    .filter((file) => file.endsWith(".sql"))
    .sort();
  return Promise.all(
    files.map(async (file, index) => {
      const match = /^(\d{4})_([a-z0-9_]+)\.sql$/.exec(file);
      if (!match || Number(match[1]) !== index + 1) {
        throw new Error(`Migrations must be numbered without gaps: ${file}`);
      }
      return {
        version: index + 1,
        name: file.slice(0, -".sql".length),
        sql: await readFile(new URL(`${directory}${file}`, root), "utf8"),
      };
    }),
  );
}

const sqliteMigrations = await readMigrations("migrations/");
const postgresMigrations = await readMigrations("migrations/postgres/");
const artifacts = new Map<string, string>();

/** One directory's migrations, in order, as an exported constant of their exact SQL. */
function embeddedMigrations(
  directory: string,
  name: string,
  migrations: Migration[],
) {
  const files = migrations
    .map((migration) => `${directory}${migration.name}.sql`)
    .join(", ");
  return `// Generated by scripts/generate-storage-schema.ts from ${files}.\nimport type { Migration } from "../migrations.js";\n\nexport const ${name}: readonly Migration[] = ${JSON.stringify(
    migrations,
    null,
    2,
  )};\n`;
}

artifacts.set(
  "src/storage/sqlite/migration.ts",
  embeddedMigrations("migrations/", "sqliteMigrations", sqliteMigrations),
);
artifacts.set(
  "src/storage/postgres/migration.ts",
  embeddedMigrations(
    "migrations/postgres/",
    "postgresMigrations",
    postgresMigrations,
  ),
);
// Wrangler applies D1's copies. D1 has no interactive transactions, so its
// guarded write batches need the connection revision in the initial table.
const connectionsEnd = "  created_at TEXT NOT NULL\n) STRICT;\n";
for (const migration of sqliteMigrations) {
  const sql =
    migration.version === 1
      ? migration.sql.replace(
          connectionsEnd,
          "  created_at TEXT NOT NULL,\n  revision INTEGER NOT NULL DEFAULT 0 CONSTRAINT connection_revision CHECK (revision BETWEEN 0 AND 9007199254740991)\n) STRICT;\n",
        )
      : migration.sql;
  if (sql === migration.sql && migration.version === 1) {
    throw new Error("The initial migration's connections table has changed");
  }
  artifacts.set(`migrations/d1/${migration.name}.sql`, sql);
}

const sqlite = createClient({ url: "file::memory:", intMode: "number" });
try {
  await migrateSqliteSchema(sqlite, sqliteMigrations, null);
  const declarations = await sqlite.execute(
    "SELECT type,name,sql FROM sqlite_master WHERE name NOT GLOB 'sqlite_*' ORDER BY type,name",
  );
  artifacts.set(
    "src/storage/sqlite/schema-manifest.ts",
    `// Generated by scripts/generate-storage-schema.ts from a fresh SQLite database.\nexport const schemaManifest = ${JSON.stringify(
      declarations.rows.map(({ type, name, sql }) => ({ type, name, sql })),
      null,
      2,
    )} as const;\n`,
  );
} finally {
  sqlite.close();
}

// Fonds owns its database's schemas, so generation uses a fresh database.
const admin = new Pool({ connectionString, connectionTimeoutMillis: 3000 });
const database = `fonds_schema_${randomUUID().replaceAll("-", "")}`;
try {
  const version = Number(
    (await admin.query("SHOW server_version_num")).rows[0].server_version_num,
  );
  if (version < 180000 || version >= 190000) {
    throw new Error("Regenerate schema declarations with PostgreSQL 18");
  }
  await admin.query(`CREATE DATABASE ${database}`);
  const url = new URL(connectionString);
  url.pathname = `/${database}`;
  const pool = new Pool({
    connectionString: url.href,
    options: `-c search_path=${FINANCIAL_SCHEMA}`,
    max: 1,
  });
  try {
    await ensurePostgresSchema(pool, FINANCIAL_SCHEMA);
    await migratePostgresSchema(pool, postgresMigrations, null);
    const manifest = async (sql: string) =>
      (
        await pool.query<{ kind: string; name: string; definition: string }>(
          sql,
        )
      ).rows.map(({ kind, name, definition }) =>
        [kind, name, definition].join("\t"),
      );
    artifacts.set(
      "src/storage/postgres/schema-manifest.ts",
      `// Generated by scripts/generate-storage-schema.ts from a fresh PostgreSQL 18 database.\nexport const schemaManifest = ${JSON.stringify(
        await manifest(schemaInspectionSql),
        null,
        2,
      )};\n\nexport const operationsManifest = ${JSON.stringify(
        await manifest(operationsInspectionSql),
        null,
        2,
      )};\n`,
    );
  } finally {
    await pool.end();
  }
} finally {
  // The database and every generated object are disposable.
  await admin.query(`DROP DATABASE IF EXISTS ${database}`);
  await admin.end();
}

for (const [path, contents] of artifacts) {
  const target = new URL(path, root);
  if (check) {
    if ((await readFile(target, "utf8")) !== contents) {
      throw new Error(`Generated storage artifact is stale: ${path}`);
    }
  } else {
    await writeFile(target, contents);
  }
}
console.log(
  check
    ? "Storage schema artifacts match."
    : "Storage schema artifacts generated.",
);
